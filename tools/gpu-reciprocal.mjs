#!/usr/bin/env node
/**
 * gpu-reciprocal — turns the oracle's measurement of the GPU's divider (_oracle/gpu_division.json,
 * from _oracle/probe_gpu_division.gd) into src/godot/gpu_reciprocal.js: the reciprocals 1/n
 * (n = 1 … 1024) that the reference machine's GPU returns and that differ from the correctly rounded
 * single-precision value, as ULP offsets. Everything else is F(1/n).
 *
 *   node tools/oracle.mjs gpu_division --windowed && node tools/gpu-reciprocal.mjs
 *
 * Checks the model before writing: every measured quotient i / n (i < n < 64) must equal
 * F(i × rcp(n)). O(n²) over the grid, O(n) over the reciprocals.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { card, paint } from './term.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, '_oracle', 'gpu_division.json');
const OUTPUT = join(ROOT, 'src', 'godot', 'gpu_reciprocal.js');

const f32 = new Float32Array(1);
const u32 = new Uint32Array(f32.buffer);
const bitsOf = (x) => ((f32[0] = x), u32[0]);
const valueOf = (bits) => ((u32[0] = bits >>> 0), f32[0]);

const entry = JSON.parse(readFileSync(SOURCE, 'utf8')).entries[0];
const reciprocal = (n) => valueOf(entry.reciprocals[n - 1]);

// The model: a / b = F(a × rcp(b)). Proved on the grid before anything is written.
let checked = 0;
entry.rows.forEach((row, k) => {
  const n = k + 1;
  row.forEach((bits, i) => {
    const model = bitsOf(Math.fround(i * reciprocal(n)));
    if (model !== bits) throw new Error(`the GPU's ${i}/${n} is not F(${i} × rcp(${n})): ${valueOf(bits)} vs ${valueOf(model)}`);
    checked += 1;
  });
});

const offsets = [];
entry.reciprocals.forEach((bits, k) => {
  const n = k + 1;
  const delta = bits - bitsOf(Math.fround(1 / n));
  if (delta !== 0) offsets.push([n, delta]);
});

const source = `/**
 * The reference machine's GPU divider — generated by tools/gpu-reciprocal.mjs from the oracle
 * (_oracle/probe_gpu_division.gd, ${entry.adapter}); do not edit by hand.
 *
 * Vulkan allows a division to be off by a few ULP, and this GPU computes a / b as a × rcp(b) with a
 * hardware reciprocal (proved on ${checked} quotients). particles.glsl decides which particle restarts
 * in a step with such a quotient (index / amount): where the reciprocal is not the correctly rounded
 * one, a particle due exactly on a step boundary starts a step earlier or later. The offsets below
 * (in ULP, for 1/n with n ≤ ${entry.reciprocals.length}) are those reciprocals; every other 1/n — and 1/x for
 * the lifetimes the game uses, measured equal — is the correctly rounded value.
 */
const F = Math.fround;
const f32 = new Float32Array(1);
const u32 = new Uint32Array(f32.buffer);

/** n → ULP offset of the GPU's 1/n from F(1/n). */
const RECIPROCAL_ULP_OFFSETS = new Map(${JSON.stringify(offsets)});

/** The GPU's single-precision 1/x. O(1). */
export function gpuReciprocal(x) {
  const correct = F(1 / F(x));
  const offset = Number.isInteger(x) ? RECIPROCAL_ULP_OFFSETS.get(x) : undefined;
  if (offset === undefined) return correct;
  f32[0] = correct;
  u32[0] += offset;
  return f32[0];
}

/** The GPU's a / b: F(a × rcp(b)). O(1). */
export function gpuDivide(a, b) {
  return F(F(a) * gpuReciprocal(b));
}
`;
writeFileSync(OUTPUT, source);
card('gpu reciprocal', [
  [paint.green('✓'), `${checked} quotients follow F(a × rcp(b))`, paint.dim(entry.adapter)],
  [paint.dim('offsets'), `${offsets.length} of ${entry.reciprocals.length} reciprocals differ from F(1/n)`],
  [paint.dim('wrote'), OUTPUT.replace(ROOT, '.')],
]);
